import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import { getReceipt, parseFinId } from '@/features/finance-data';
import { ReceiptActions } from '@/features/finance-extras';
import { money } from '@/lib/finance-validation';
import { requireContext } from '@/lib/server-context';

export const metadata: Metadata = { title: 'Fee receipt' };

export default async function ReceiptPage({ params }: { params: Promise<{ id: string }> }) {
  const id = parseFinId((await params).id);
  if (id === null) notFound();
  const { supabase } = await requireContext();
  const r = await getReceipt(supabase, id);
  if (!r) notFound();
  const void_ = r.receipt_status !== 'ISSUED';
  return (
    <div className="max-w-2xl space-y-4">
      <ReceiptActions receipt={r} />
      <article aria-label={`Receipt ${r.receipt_number}`} className="relative space-y-4 rounded-lg border border-border bg-card p-6 print:border-0 print:p-0">
        {void_ && <div className="absolute right-6 top-6 rotate-6 rounded border-2 border-destructive px-3 py-1 text-lg font-bold uppercase text-destructive">{r.receipt_status}</div>}
        <header className="border-b border-border pb-3">
          <h1 className="text-xl font-semibold">Fee receipt</h1>
          <p className="text-sm text-muted-foreground">No. <span className="font-medium text-foreground">{r.receipt_number}</span> · {new Date(r.receipt_date).toLocaleDateString()}</p>
        </header>
        <dl className="grid grid-cols-[9rem_1fr] gap-y-1 text-sm">
          <dt className="text-muted-foreground">Student</dt><dd>{r.student_name} ({r.student_number})</dd>
          <dt className="text-muted-foreground">Account</dt><dd>{r.account_number}</dd>
          <dt className="text-muted-foreground">Payment</dt><dd>{r.transaction_number} · {r.payment_mode} · {new Date(r.transaction_date).toLocaleDateString()}</dd>
          {r.bank_reference && (<><dt className="text-muted-foreground">Reference</dt><dd>{r.bank_reference}</dd></>)}
          {r.payer_name && (<><dt className="text-muted-foreground">Paid by</dt><dd>{r.payer_name}</dd></>)}
        </dl>
        {r.allocations.length > 0 && (
          <table className="w-full text-sm">
            <thead className="border-b border-border text-left"><tr><th scope="col" className="py-1 font-medium">Towards</th><th scope="col" className="py-1 text-right font-medium">Amount</th></tr></thead>
            <tbody>{r.allocations.map((a, i) => <tr key={i} className="border-b border-border last:border-0"><td className="py-1">{a.fee}</td><td className="py-1 text-right tabular-nums">{money(a.amount)}</td></tr>)}</tbody>
          </table>
        )}
        <p className="text-right text-lg font-semibold tabular-nums">Total received {money(r.receipt_amount)}</p>
        {r.cancellation_reason && <p className="text-sm text-muted-foreground">Reason: {r.cancellation_reason}</p>}
        <p className="text-xs text-muted-foreground print:hidden">This receipt is generated by SIMS; the amounts come from the recorded payment, not from this page.</p>
      </article>
    </div>
  );
}
