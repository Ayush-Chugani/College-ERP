"""Assemble supabase/migrations/*.sql from tools/work/pg_statements.json (run tools/translate.py first)."""
import json, os, re

W = r'D:\Sims_2\tools\work'
OUT = r'D:\Sims_2\supabase\migrations'
os.makedirs(OUT, exist_ok=True)
import re as _re
for f in os.listdir(OUT):
    # only the generated schema migrations 001-016; 017+ are hand-written or produced by tools/build_rls.py
    if _re.match(r'^0(0\d|1[0-6])_.*\.sql$', f):
        os.remove(os.path.join(OUT, f))

stmts = json.load(open(os.path.join(W, 'pg_statements.json')))
notes = json.load(open(os.path.join(W, 'translation_notes.json')))

# (file, first source line, last source line exclusive, description) - boundaries follow the SQL's own section banners
BUCKETS = [
    ('001_common_reference_and_institution', 1, 231, 'Source sections 1-2: common reference data, university/institution structure'),
    ('002_academic_calendar_and_curriculum', 231, 363, 'Source sections 3-4'),
    ('003_student_employee_admission_registration', 363, 898, 'Source sections 5-7: student/staff roots, admission, registration'),
    ('004_teaching_attendance_assessment_feedback', 898, 1259, 'Source sections 8-12: teaching, timetable, attendance, assessment, results, feedback, mentoring, grievance'),
    ('005_documents_and_communication', 1259, 1370, 'Source sections 13-14'),
    ('006_identity_rbac_audit', 1370, 1857, 'Source section 15 (legacy RBAC catalogue, audit) incl. RBAC seed data'),
    ('007_employee_hr_profile', 1857, 2421, 'Source section 16'),
    ('008_student_finance', 2421, 3068, 'Source section 17 (tables, fee seed data, views)'),
    ('009_indexes_and_file_metadata', 3068, 3474, 'Source section 18: performance indexes, file_object extension'),
    ('010_staff_profile_and_research', 3474, 4426, 'Source sections 19-32'),
    ('011_evidence_and_seed_data', 4426, 4979, 'Source sections 33-36'),
    ('012_staff_views_and_indexes', 4979, 5181, 'Source sections 37-38'),
    ('013_student_activity_and_evidence', 5181, 10 ** 9, 'Source section 40'),
]

HEADER = '-- Generated by tools/build_migrations.py from SIMS-DatabaseWithoutLessonPlan.sql\n-- {desc}\n-- Source line ranges: {lo}-{hi}\n\n'
DOMAINS = """-- MySQL UNSIGNED integer ranges as domains (identity/PK columns use the narrowest plain integer type instead).
CREATE DOMAIN u8 AS smallint CHECK (VALUE BETWEEN 0 AND 255);
CREATE DOMAIN u16 AS integer CHECK (VALUE BETWEEN 0 AND 65535);
CREATE DOMAIN u24 AS integer CHECK (VALUE BETWEEN 0 AND 16777215);
CREATE DOMAIN u32 AS bigint CHECK (VALUE BETWEEN 0 AND 4294967295);
-- NOTE: BIGINT UNSIGNED maps to bigint (non-negative); values above 2^63-1 are not representable. No such values are expected.
CREATE DOMAIN u64 AS bigint CHECK (VALUE >= 0);
-- MySQL YEAR range 1901..2155
CREATE DOMAIN u_year AS smallint CHECK (VALUE BETWEEN 1901 AND 2155);

"""

written = []
for name, lo, hi, desc in BUCKETS:
    body = [s['sql'] for s in stmts if s['sql'] and lo <= s['line'] < hi and s['kind'] != 'TRIGGER_BLOCK']
    text = HEADER.format(desc=desc, lo=lo, hi=min(hi, 5647)) + (DOMAINS if name.startswith('001') else '') + '\n\n'.join(body) + '\n'
    open(os.path.join(OUT, name + '.sql'), 'w', encoding='utf-8', newline='\n').write(text)
    written.append(name)

# 014 triggers + updated_at
trg = open(os.path.join(W, 'triggers_pg.sql'), encoding='utf-8').read()
upd = '\n-- ON UPDATE CURRENT_TIMESTAMP replacement for the 37 columns that used it\n'
for tbl, col in notes['updated_at']:
    assert col == 'updated_at', (tbl, col)
    upd += f'CREATE TRIGGER trg_{tbl}_touch_updated_at BEFORE UPDATE ON {tbl} FOR EACH ROW EXECUTE FUNCTION sims_touch_updated_at();\n'
open(os.path.join(OUT, '014_triggers_and_integrity.sql'), 'w', encoding='utf-8', newline='\n').write(
    '-- Hand-ported triggers (source lines 3070-3353) and updated_at maintenance\n\n' + trg + upd)

# 015 identity sequence resync (seed rows insert explicit ids, if any)
seq = '-- Advance identity sequences past any explicitly inserted seed ids\nDO $$\nDECLARE r record;\nBEGIN\n    FOR r IN\n        SELECT c.table_name, c.column_name FROM information_schema.columns c\n        WHERE c.table_schema = \'public\' AND c.is_identity = \'YES\'\n    LOOP\n        EXECUTE format(\'SELECT setval(pg_get_serial_sequence(%L, %L), COALESCE(MAX(%I), 1), MAX(%I) IS NOT NULL) FROM public.%I\',\n            \'public.\' || r.table_name, r.column_name, r.column_name, r.column_name, r.table_name);\n    END LOOP;\nEND $$;\n'
open(os.path.join(OUT, '015_identity_sequence_resync.sql'), 'w', encoding='utf-8', newline='\n').write(seq)

# 016 deny-by-default RLS baseline (policies come with the RLS phase)
rls = """-- Baseline: RLS on for every public table, no policies => no client access until policies are added in the RLS phase.
-- Views are security_invoker, so they inherit this. Privileged server code uses the service role (bypasses RLS).
DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.tablename);
    END LOOP;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
        REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
        REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM anon;
    END IF;
END $$;
"""
open(os.path.join(OUT, '016_rls_deny_by_default.sql'), 'w', encoding='utf-8', newline='\n').write(rls)
print(sorted(os.listdir(OUT)))
