// Generates docs/DATABASE_SCHEMA.md from the migrated catalogue (embedded PostgreSQL): every table with its module, columns, keys, foreign keys, checks and policies count, plus views and functions.
//   node tools/validate/schema_doc.mjs [--check]     (--check fails when the committed file is out of date)
import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';

const modules = JSON.parse(fs.readFileSync('tools/rls/table_module.json', 'utf8'));
const db = new PGlite();
await db.exec(fs.readFileSync('tests/db/supabase-stub.ts', 'utf8').split('`')[1]);
const files = fs.readdirSync('supabase/migrations').filter((x) => x.endsWith('.sql')).sort();
for (const f of files) await db.exec(fs.readFileSync(`supabase/migrations/${f}`, 'utf8'));
const q = async (s) => (await db.query(s)).rows;

const cols = await q(`select c.relname t, a.attnum n, a.attname col, format_type(a.atttypid, a.atttypmod) typ, a.attnotnull nn, a.atthasdef hasdef, a.attgenerated gen
  from pg_attribute a join pg_class c on c.oid = a.attrelid where c.relnamespace = 'public'::regnamespace and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped order by c.relname, a.attnum`);
const cons = await q(`select c.relname t, con.contype ty, con.conname name, pg_get_constraintdef(con.oid) def from pg_constraint con join pg_class c on c.oid = con.conrelid where c.relnamespace = 'public'::regnamespace order by c.relname, con.contype, con.conname`);
const pol = Object.fromEntries((await q(`select tablename t, count(*)::int n from pg_policies where schemaname = 'public' group by 1`)).map((r) => [r.t, r.n]));
const rls = Object.fromEntries((await q(`select relname t, relrowsecurity r from pg_class where relnamespace = 'public'::regnamespace and relkind = 'r'`)).map((r) => [r.t, r.r]));
const views = await q(`select viewname v from pg_views where schemaname = 'public' order by 1`);
const fns = await q(`select p.proname n, pg_get_function_identity_arguments(p.oid) a, p.prosecdef sd from pg_proc p where p.pronamespace = 'public'::regnamespace order by 1`);
const trig = await q(`select c.relname t, count(*)::int n from pg_trigger g join pg_class c on c.oid = g.tgrelid where not g.tgisinternal and c.relnamespace = 'public'::regnamespace group by 1`);
const trigBy = Object.fromEntries(trig.map((r) => [r.t, r.n]));

const tables = [...new Set(cols.map((c) => c.t))].sort();
const byModule = {};
for (const t of tables) (byModule[modules[t] ?? 'OTHER'] ??= []).push(t);

let md = `# Database schema\n\nGenerated by \`node tools/validate/schema_doc.mjs\` from migrations 001-${files.length ? files[files.length - 1].slice(0, 3) : '?'} applied to an embedded PostgreSQL. **Do not edit by hand.**\n\n`;
md += `${tables.length} tables, ${views.length} views, ${fns.length} public functions (RPCs), ${Object.values(pol).reduce((a, b) => a + b, 0)} row level security policies. Types ending in \`u8\`, \`u16\`, \`u32\`, \`u64\` are domains that restrict the range of unsigned MySQL integers.\n\n`;
md += `## Contents\n\n${Object.keys(byModule).sort().map((m) => `- [${m}](#${m.toLowerCase().replace(/_/g, '-')}) (${byModule[m].length} tables)`).join('\n')}\n- [Views](#views)\n- [Functions](#functions)\n\n`;
for (const m of Object.keys(byModule).sort()) {
  md += `## ${m}\n\n`;
  for (const t of byModule[m]) {
    const tc = cons.filter((c) => c.t === t);
    const pk = tc.find((c) => c.ty === 'p')?.def.replace(/^PRIMARY KEY /, '') ?? '';
    md += `### ${t}\n\nRLS ${rls[t] ? 'on' : '**off**'} · ${pol[t] ?? 0} policies · ${trigBy[t] ?? 0} triggers${pk ? ` · key ${pk}` : ''}\n\n| Column | Type | Null | Notes |\n|---|---|---|---|\n`;
    for (const c of cols.filter((x) => x.t === t)) md += `| ${c.col} | ${c.typ} | ${c.nn ? 'no' : 'yes'} | ${c.gen ? 'generated' : c.hasdef ? 'default' : ''} |\n`;
    const extra = tc.filter((c) => c.ty !== 'p');
    if (extra.length) md += `\n${extra.map((c) => `- ${c.ty === 'f' ? 'FK' : c.ty === 'u' ? 'UNIQUE' : c.ty === 'c' ? 'CHECK' : c.ty}: \`${c.def.length > 220 ? c.def.slice(0, 217) + '…' : c.def}\``).join('\n')}\n`;
    md += '\n';
  }
}
md += `## Views\n\n${views.map((v) => `- \`${v.v}\` (security invoker)`).join('\n')}\n\n## Functions\n\nPublic functions are the RPCs of [API_DOCUMENTATION.md](API_DOCUMENTATION.md). \`definer\` functions run with their owner's rights and check permissions inside.\n\n| Function | Arguments | Kind |\n|---|---|---|\n`;
for (const f of fns) md += `| ${f.n} | ${f.a.replace(/\|/g, '/')} | ${f.sd ? 'definer' : 'invoker'} |\n`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync('docs/DATABASE_SCHEMA.md') ? fs.readFileSync('docs/DATABASE_SCHEMA.md', 'utf8') : '';
  if (cur !== md) { console.error('docs/DATABASE_SCHEMA.md is out of date: run node tools/validate/schema_doc.mjs'); process.exit(1); }
  console.log('docs/DATABASE_SCHEMA.md is up to date');
} else {
  fs.writeFileSync('docs/DATABASE_SCHEMA.md', md);
  console.log(`wrote docs/DATABASE_SCHEMA.md (${md.length} bytes, ${tables.length} tables)`);
}
