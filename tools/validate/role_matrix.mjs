// Generates docs/ROLE_PERMISSION_MATRIX.md from the migrated seed: for every role its level and, per access module, which actions it holds.
//   node tools/validate/role_matrix.mjs [--check]     (--check fails when the committed file is out of date)
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';
import fs from 'node:fs';

const db = new PGlite({ extensions: { pgcrypto } });
await db.exec(fs.readFileSync('tests/db/supabase-stub.ts', 'utf8').split('`')[1]);
const files = fs.readdirSync('supabase/migrations').filter((x) => x.endsWith('.sql')).sort();
for (const f of files) await db.exec(fs.readFileSync(`supabase/migrations/${f}`, 'utf8'));
const q = async (s) => (await db.query(s)).rows;

const roles = await q(`select role_id, role_code, role_name, role_level, role_category from role order by role_category, role_code`);
const grants = await q(`select r.role_code, split_part(p.permission_code, '.', 1) m, split_part(p.permission_code, '.', 3) a, split_part(p.permission_code, '.', 2) res
  from role_permission rp join role r on r.role_id = rp.role_id join permission p on p.permission_id = rp.permission_id where rp.permission_effect = 'ALLOW'`);
const ABBR = { CREATE: 'C', READ: 'R', UPDATE: 'U', DELETE: 'D', APPROVE: 'A', VERIFY: 'V', EXPORT: 'E', CONFIGURE: 'G' };
const modules = [...new Set(grants.map((g) => g.m))].sort();
const cell = (role, m) => {
  const acts = new Set(grants.filter((g) => g.role_code === role && g.m === m).map((g) => g.a));
  return acts.size ? Object.keys(ABBR).filter((a) => acts.has(a)).map((a) => ABBR[a]).join('') : '';
};

let md = `# Role and permission matrix\n\nGenerated by \`node tools/validate/role_matrix.mjs\` from migrations 001-${files[files.length - 1].slice(0, 3)}. Do not edit by hand.\n\n`;
md += `A cell lists the actions the role is granted anywhere in that access module: **C**reate, **R**ead, **U**pdate, **D**elete, **A**pprove, **V**erify, **E**xport, confi**G**ure. `;
md += `A grant applies at the scope of the user's role assignment (self, programme, department, campus, institution or global); some resources inside a module (for example \`FEES.FEE_REFUND\`) are granted separately, see the per-role list in the database. `;
md += `Sensitive resources need their specific grant: \`ALL\` is not enough.\n\n`;
md += `## Roles\n\n| Role | Level | Category | Modules |\n|---|---|---|---|\n`;
for (const r of roles) {
  const mods = modules.filter((m) => cell(r.role_code, m)).length;
  md += `| \`${r.role_code}\` | ${r.role_level} | ${r.role_category} | ${mods || 'none (technical role)'} |\n`;
}
md += `\n## Matrix\n\n| Role | ${modules.join(' | ')} |\n|---|${modules.map(() => '---').join('|')}|\n`;
for (const r of roles) md += `| \`${r.role_code}\` | ${modules.map((m) => cell(r.role_code, m)).join(' | ')} |\n`;
md += `\n## Fees in detail (migrations 008 and 052)\n\n| Role | Resource | Actions |\n|---|---|---|\n`;
const fees = grants.filter((g) => g.m === 'FEES');
for (const r of roles) {
  const own = fees.filter((g) => g.role_code === r.role_code);
  for (const res of [...new Set(own.map((g) => g.res))].sort()) {
    const acts = new Set(own.filter((g) => g.res === res).map((g) => g.a));
    md += `| \`${r.role_code}\` | ${res} | ${Object.keys(ABBR).filter((a) => acts.has(a)).map((a) => ABBR[a]).join('')} |\n`;
  }
}
md += `\nNot in the matrix because they are decided by identity, not by a grant: a student or employee acting on their own record (profile, documents, grievances, feedback, HR records, activities).\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync('docs/ROLE_PERMISSION_MATRIX.md') ? fs.readFileSync('docs/ROLE_PERMISSION_MATRIX.md', 'utf8') : '';
  if (cur !== md) { console.error('docs/ROLE_PERMISSION_MATRIX.md is out of date: run node tools/validate/role_matrix.mjs'); process.exit(1); }
  console.log('docs/ROLE_PERMISSION_MATRIX.md is current');
} else {
  fs.writeFileSync('docs/ROLE_PERMISSION_MATRIX.md', md);
  console.log(`wrote docs/ROLE_PERMISSION_MATRIX.md (${roles.length} roles, ${modules.length} modules)`);
}
