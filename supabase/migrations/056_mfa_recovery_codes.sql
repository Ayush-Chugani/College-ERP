-- MFA recovery codes. Hand-written (not from the MySQL source). Supabase Auth owns the TOTP factors and has no recovery codes, so a person who loses the authenticator device would be locked out.
--
-- DESIGN
--  * mfa_recovery_generate() (needs a fully signed-in session, i.e. aal2 when MFA is on) replaces the person's unused codes with 10 new random ones and returns them ONCE. Only salted bcrypt hashes are stored.
--  * mfa_recovery_use(code) is callable at aal1 (the person has passed the password step but cannot give a TOTP code): a valid unused code removes the person's TOTP factors and switches the enforcement
--    off (user_account.multi_factor_enabled = false) so they can sign in and enrol a new authenticator; all their remaining recovery codes are deleted. The event is written to activity_audit.
--  * Brute force: at most 5 wrong codes per person in 15 minutes (mfa_recovery_attempt); the check happens before any hash is compared.
--
-- ASSUMPTIONS (KNOWN_ISSUES KI-66): a code has 10 characters from an unambiguous alphabet (about 50 bits), shown as XXXXX-XXXXX; the factor removal needs the database owner role to be able to delete from
-- auth.mfa_factors, which is the case on Supabase but has not been tried against the live project; using a code does not notify the person by email.

CREATE TABLE sims_private.mfa_recovery_code (
    code_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.user_account(user_id) ON DELETE CASCADE,
    code_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    used_at timestamptz
);
CREATE INDEX idx_mfa_recovery_code_user ON sims_private.mfa_recovery_code (user_id) WHERE used_at IS NULL;
CREATE TABLE sims_private.mfa_recovery_attempt (
    attempt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.user_account(user_id) ON DELETE CASCADE,
    attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_mfa_recovery_attempt_user ON sims_private.mfa_recovery_attempt (user_id, attempted_at);
REVOKE ALL ON sims_private.mfa_recovery_code, sims_private.mfa_recovery_attempt FROM PUBLIC, anon, authenticated;

-- the signed-in person, without the aal2 requirement (needed to use a code at aal1)
CREATE FUNCTION sims_private.user_id_any_aal() RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT m.user_id FROM sims_private.auth_identity_map m JOIN public.user_account u ON u.user_id = m.user_id
    WHERE m.auth_user_id = auth.uid() AND u.account_status = 'ACTIVE' AND (u.locked_until IS NULL OR u.locked_until <= now())
$$;
REVOKE ALL ON FUNCTION sims_private.user_id_any_aal() FROM PUBLIC, anon, authenticated;

CREATE FUNCTION public.mfa_recovery_generate() RETURNS text[]
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_uid bigint := sims_private.current_user_id();
    v_alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
    v_codes text[] := '{}'; v_code text; i integer; j integer; v_bytes bytea;
BEGIN
    IF v_uid IS NULL THEN RAISE EXCEPTION 'Not authorised' USING ERRCODE = '42501'; END IF;
    DELETE FROM sims_private.mfa_recovery_code WHERE user_id = v_uid;
    FOR i IN 1..10 LOOP
        v_bytes := extensions.gen_random_bytes(10);
        v_code := '';
        FOR j IN 0..9 LOOP v_code := v_code || substr(v_alphabet, (get_byte(v_bytes, j) % 31) + 1, 1); END LOOP;
        v_code := substr(v_code, 1, 5) || '-' || substr(v_code, 6, 5);
        INSERT INTO sims_private.mfa_recovery_code (user_id, code_hash) VALUES (v_uid, extensions.crypt(v_code, extensions.gen_salt('bf', 8)));
        v_codes := v_codes || v_code;
    END LOOP;
    INSERT INTO activity_audit (user_id, module_code, action_code, entity_name, entity_id, details) VALUES (v_uid, 'IAM', 'MFA_RECOVERY_CODES_GENERATED', 'user_account', v_uid::text, '{}'::jsonb);
    RETURN v_codes;
END $$;

CREATE FUNCTION public.mfa_recovery_status() RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_uid bigint := sims_private.current_user_id();
BEGIN
    IF v_uid IS NULL THEN RAISE EXCEPTION 'Not authorised' USING ERRCODE = '42501'; END IF;
    RETURN jsonb_build_object('unused', (SELECT count(*) FROM sims_private.mfa_recovery_code WHERE user_id = v_uid AND used_at IS NULL),
                              'generated_at', (SELECT max(created_at) FROM sims_private.mfa_recovery_code WHERE user_id = v_uid));
END $$;

CREATE FUNCTION public.mfa_recovery_use(p_code text) RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_uid bigint := sims_private.user_id_any_aal(); v_code text := upper(regexp_replace(COALESCE(p_code, ''), '[\s-]', '', 'g')); r record; v_ok boolean := false; v_norm text;
BEGIN
    IF v_uid IS NULL OR NOT EXISTS (SELECT 1 FROM user_account WHERE user_id = v_uid AND multi_factor_enabled) THEN RAISE EXCEPTION 'Not authorised' USING ERRCODE = '42501'; END IF;
    DELETE FROM sims_private.mfa_recovery_attempt WHERE attempted_at < now() - interval '1 day';
    IF (SELECT count(*) FROM sims_private.mfa_recovery_attempt WHERE user_id = v_uid AND attempted_at > now() - interval '15 minutes') >= 5 THEN
        RAISE EXCEPTION 'Too many wrong codes. Try again in 15 minutes.' USING ERRCODE = '45000';
    END IF;
    IF length(v_code) = 10 THEN
        v_norm := substr(v_code, 1, 5) || '-' || substr(v_code, 6, 5);
        FOR r IN SELECT code_id, code_hash FROM sims_private.mfa_recovery_code WHERE user_id = v_uid AND used_at IS NULL ORDER BY code_id FOR UPDATE LOOP
            IF r.code_hash = extensions.crypt(v_norm, r.code_hash) THEN
                UPDATE sims_private.mfa_recovery_code SET used_at = now() WHERE code_id = r.code_id;
                v_ok := true;
                EXIT;
            END IF;
        END LOOP;
    END IF;
    IF NOT v_ok THEN
        INSERT INTO sims_private.mfa_recovery_attempt (user_id) VALUES (v_uid);
        RETURN false; -- committed: the function returns normally so the attempt is recorded
    END IF;
    DELETE FROM auth.mfa_factors WHERE user_id = auth.uid();
    UPDATE user_account SET multi_factor_enabled = false WHERE user_id = v_uid;
    DELETE FROM sims_private.mfa_recovery_code WHERE user_id = v_uid;
    INSERT INTO activity_audit (user_id, module_code, action_code, entity_name, entity_id, details) VALUES (v_uid, 'IAM', 'MFA_RECOVERY_USED', 'user_account', v_uid::text, '{}'::jsonb);
    RETURN true;
END $$;

REVOKE ALL ON FUNCTION public.mfa_recovery_generate(), public.mfa_recovery_status(), public.mfa_recovery_use(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.mfa_recovery_generate(), public.mfa_recovery_status(), public.mfa_recovery_use(text) TO authenticated;
